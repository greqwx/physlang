// parseUnit разбирает запись единицы из файла задачи
// степени можно писать как ^2, ² или ³, умножение как ·, × или *, деление косой чертой
// скобки просто выбрасываются, поэтомы Дж/(кг*цлс) и Дж/кг/цлс дают одно и то же
func parseUnit(s string) (*unit, error) {
	orig := strings.TrimSpace(s)
	if orig == "" {
		return &unit{f: 1}, nil
	}
	// сначала приводим запись к одному виду: степени, знаки умножения и пробелы
	norm := strings.NewReplacer("²", "^2", "³", "^3", "·", "*", "×", "*", "⋅", "*", " ", "").Replace(orig)
	norm = strings.NewReplacer("(", "", ")", "").Replace(norm)
	parts := strings.Split(norm, "/")
	res := &unit{f: 1}
	if err := multiplyInto(res, parts[0], 1); err != nil {
		return nil, fmt.Errorf("единица «%s»: %v", orig, err)
	}
	// всё после первой косой черты считается знаменателем, как принято в записи
	// вроде Дж/кг·цлс, где деление относится ко всей правой части
	for _, p := range parts[1:] {
		if err := multiplyInto(res, p, -1); err != nil {
			return nil, fmt.Errorf("единица «%s»: %v", orig, err)
		}
	}
	return res, nil
}

// multiplyInto домножает результат на один множитель записи
// sign равен -1 для знаменателя, чтобы степени вычитались
func multiplyInto(res *unit, part string, sign int) error {
	if part == "" {
		return fmt.Errorf("пустая единица")
	}
	for _, f := range strings.Split(part, "*") {
		if f == "" {
			return fmt.Errorf("пустая единица")
		}
		base := f
		exp := 1
		// степень стоит после знака ^, без неё множитель входит в первой степени
		if i := strings.IndexByte(f, '^'); i >= 0 {
			base = f[:i]
			n, err := strconv.Atoi(f[i+1:])
			if err != nil {
				return fmt.Errorf("плохая степень «%s»", f)
			}
			exp = n
		}
		a, ok := unitAliases[strings.ToLower(base)]
		if !ok {
			return fmt.Errorf("неизвестная единица «%s»", base)
		}
		p := (&unit{d: a.d, f: a.f}).pow(exp * sign)
		*res = *res.mul(p)
	}
	return nil
}
